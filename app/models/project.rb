class Project < ApplicationRecord
  # ===========================================================================
  # SOLID QUEUE — Active Record callbacks that enqueue jobs
  # ===========================================================================
  # after_create_commit  → fires after INSERT is committed to DB
  # after_update_commit  → fires after UPDATE is committed to DB
  #
  # These use Solid Queue under the hood (configured via config/queue.yml)
  # Jobs are persisted to queue.sqlite3, NOT in memory — survives server restart
  # ===========================================================================

  # 1. Immediately enqueue a high-priority notification job (urgent queue)
  after_create_commit :notify_creation

  # 2. Schedule archiving to run 10 seconds later (default queue)
  after_create_commit :schedule_archive

  # 3. TURBO STREAMS: When a project is updated (including archived=true),
  #    broadcast a remove so it disappears from the live projects list
  after_update_commit -> { broadcast_remove_to "projects_list" }

  # 4. TURBO STREAMS: When a project is created, broadcast append to the list
  after_create_commit -> { broadcast_append_to "projects_list", target: "projects" }

  # ===========================================================================
  # RAILS 8.1 — STRUCTURED EVENT REPORTING
  # ===========================================================================
  # Rails.event.notify emits a structured event to all registered subscribers.
  # Events are named with dot-notation (domain.action) and carry a payload hash.
  #
  # The LogEventSubscriber (config/initializers/event_subscriber.rb) receives
  # these and stores them in Solid Cache so the /events page can display them.
  #
  # Benefits over Rails.logger.info:
  #   - Machine-readable structured payload (not a plain string)
  #   - Can be routed to multiple subscribers (log, metrics, audit trail, etc.)
  #   - Supports tags and context (e.g. request_id, user_id)
  #   - Source location (file + line) is automatically recorded
  # ===========================================================================
  after_create_commit  :emit_project_created_event
  after_update_commit  :emit_project_updated_event

  # ===========================================================================
  # RAILS 8.1 — MARKDOWN RENDERING
  # ===========================================================================
  # Rails 8.1 added `render markdown: object` in controllers.
  # The object must respond to #to_markdown — Rails calls this method and
  # converts the returned Markdown string to HTML for display.
  #
  # Access via: GET /projects/:id.md
  #
  # The notes field stores user-authored Markdown content entered in the form.
  # We compose a full document including title, metadata, description, and notes.
  # ===========================================================================
  def to_markdown
    <<~MARKDOWN
      # #{title}

      **Status:** #{archived? ? "🗄️ Archived" : "✅ Active"}
      **Created:** #{created_at&.strftime("%d %B %Y")}
      **Last Updated:** #{updated_at&.strftime("%d %B %Y at %H:%M")}

      ## Description

      #{description.presence || "_No description provided._"}

      ## Notes

      #{notes.presence || "_No notes added yet._"}

      ---

      *Generated by Rails 8.1 Markdown Rendering — `render markdown: @project`*
    MARKDOWN
  end

  private

  def notify_creation
    # Runs immediately on the :urgent queue
    NotifyProjectCreatedJob.perform_later(id)
  end

  def schedule_archive
    # Runs 10 seconds later on the :default queue
    # Demonstrates: .set(wait:) — Solid Queue's delayed job scheduling
    ArchiveProjectJob.set(wait: 10.seconds).perform_later(id)
  end

  # ---------------------------------------------------------------------------
  # Rails 8.1 Structured Event: emitted on project creation
  # Payload is a plain Ruby hash — serialisable, loggable, queryable
  # ---------------------------------------------------------------------------
  def emit_project_created_event
    Rails.event.notify(
      "project.created",
      project_id:   id,
      title:        title,
      description:  description.to_s.truncate(80),
      created_at:   created_at.iso8601
    )
  end

  # ---------------------------------------------------------------------------
  # Rails 8.1 Structured Event: emitted on project updates (archive, edit, etc.)
  # ---------------------------------------------------------------------------
  def emit_project_updated_event
    Rails.event.notify(
      "project.updated",
      project_id:   id,
      title:        title,
      archived:     archived,
      updated_at:   updated_at.iso8601
    )
  end
end
